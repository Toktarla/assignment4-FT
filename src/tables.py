def _sim_row(sim: dict) -> list[str]:
    rec = sim["recovery"]
    login = "blocked" if not any(x["event"] == "Successful login" for x in sim["applied"]) else "allowed"
    rpo = "-" if rec["rpo_minutes"] is None else str(rec["rpo_minutes"])
    rto = "-" if rec["rto_minutes"] is None else str(rec["rto_minutes"])
    return [
        sim["mode"],
        login,
        str(sim["files_modified"]),
        str(sim["files_encrypted"]),
        "yes" if sim["backup_intact"] else "no",
        str(len(sim["outbound"])),
        "yes" if sim["av_enabled"] else "no",
        rpo,
        rto,
    ]
